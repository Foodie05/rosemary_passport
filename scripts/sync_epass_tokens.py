#!/usr/bin/env python3
"""Keep standalone authorization pages on the pinned web design tokens."""
from pathlib import Path
import subprocess
root = Path(__file__).resolve().parents[1]
source = root / 'web/src/design/rosemary-tokens.css'
target = root / 'apps/passport_server/lib/src/utils/epass_tokens.dart'
target.write_text('// Generated by scripts/sync_epass_tokens.py; do not edit.\n'
                  '// Rosemary Design v2.0.0-beta.2-banner.2 (a36510e38277a2f84ab4150e074bbfbee55ddefd).\n'
                  "const epassTokens = r'''\n" + source.read_text() + "''';\n")

# Resolve the same semantic source into SDK constants; no algorithmic seed colors.
import hashlib
import re

css = source.read_text()
colors = ['canvas', 'surface', 'surface-subtle', 'text', 'text-secondary',
          'text-tertiary', 'border', 'border-control', 'accent', 'accent-hover',
          'on-accent', 'accent-subtle', 'focus', 'danger', 'danger-subtle',
          'warning', 'warning-subtle']
def camel(value):
    parts = value.split('-')
    return parts[0] + ''.join(part.title() for part in parts[1:])
def properties(block):
    return dict(re.findall(r'(--r-[\w-]+):\s*([^;]+);', block))
def resolve(values, name):
    value = values[name].strip()
    while value.startswith('var('):
        value = values[value[4:-1]].strip()
    return value
light, dark = css.split('.dark, [data-theme="dark"] {')
code = ['// Generated by scripts/sync_epass_tokens.py; do not edit.',
        '// Rosemary Design v2.0.0-beta.2-banner.2; source SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
        "import 'package:flutter/material.dart';", '']
for theme, block in [('Light', light), ('Dark', dark)]:
    values = properties(block)
    code.append(f'class RosmEpass{theme}Tokens {{')
    for name in colors:
        value = resolve(values, '--r-semantic-color-' + name)
        code.append(f'  static const {camel(name)} = Color(0xFF{value[1:].upper()});')
    code.append('}\n')
values = properties(light)
code.append('class RosmEpassMotion {')
for name in ['fast', 'settle', 'press', 'hover', 'enter', 'exit', 'panel', 'spin']:
    value = resolve(values, '--r-semantic-motion-' + name)
    code.append(f'  static const {name} = Duration(milliseconds: {value[:-2]});')
for name in ['standard', 'entrance', 'exit-ease']:
    value = resolve(values, '--r-semantic-motion-' + name)
    code.append(f'  static const {camel(name)} = Cubic({value[13:-1]});')
code.append('}\nclass RosmEpassGeometry {')
for name in ['control', 'panel']:
    value = resolve(values, '--r-semantic-radius-' + name)
    code.append(f'  static const {name} = {value[:-2]}.0;')
code.append('}\n')
(root / 'packages/rosm_passport_flutter/lib/src/epass_tokens.dart').write_text('\n'.join(code))

# Make regeneration byte-stable with the repository formatter.
subprocess.run(["dart", "format", str(target), str(root / "packages/rosm_passport_flutter/lib/src/epass_tokens.dart")], check=True)
