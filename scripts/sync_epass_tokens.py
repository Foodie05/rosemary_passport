#!/usr/bin/env python3
"""Generate web, standalone and Flutter roles from the Epass theme + Forma contract."""
from pathlib import Path
import hashlib
import base64
import json
import subprocess
import textwrap

root = Path(__file__).resolve().parents[1]
design = root / 'web/src/design'
source = json.loads((design / 'forma-source.json').read_text())
product = json.loads((design / 'epass-theme.json').read_text())
roles = list(source['themes']['light'])
assert len(roles) == 24
for palette in product['themes'].values():
    assert set(palette) == set(roles)
    assert all(len(v) == 7 and v.startswith('#') and int(v[1:], 16) >= 0 for v in palette.values())

def camel(s):
    a, *b = s.split('-')
    return a + ''.join(x.title() for x in b)

aliases = {'surface-subtle':'raised','text':'ink','text-secondary':'muted','text-tertiary':'muted','border-control':'control','accent':'primary','on-accent':'on-primary','accent-subtle':'primary-soft','danger-subtle':'danger-soft','warning-subtle':'warning-soft','success-subtle':'success-soft','info-subtle':'info-soft','disabled':'muted'}
motion = source['motion']
old_motion = {'instant':0,'fast':motion['state'],'settle':motion['page'],'press':motion['instantFeedback'],'hover':motion['instantFeedback'],'enter':motion['transition'],'exit':motion['exit'],'panel':motion['drawerEnterMs'],'spin':motion['loadingCycleMs'],'tabs':motion['tabsMs'],'loading-delay':300,'progress':motion['progressMs']}
css = ['/* Generated by scripts/sync_epass_tokens.py. Forma 1.2.0 / SDK 0.4.0. */']
for mode, palette in product['themes'].items():
    css.append((':root, [data-theme="light"]' if mode == 'light' else '.dark, [data-theme="dark"]') + ' {')
    for name, value in palette.items():
        css.append(f'  --r-semantic-color-{name}: {value};')
    for name, role in aliases.items(): css.append(f'  --r-semantic-color-{name}: var(--r-semantic-color-{role});')
    css += ['  --r-semantic-color-accent-hover: var(--r-semantic-color-primary);', '  --r-semantic-color-overlay: #000000;']
    for i, role in enumerate(['primary','sun','info','warning'],1):css.append(f'  --r-semantic-color-chart-{["one","two","three","four"][i-1]}: var(--r-semantic-color-{role});')
    css.append('}')
css.append(':root {')
for n in source['space']:css.append(f'  --r-semantic-space-{n}: {n}px;')
for name,val in {'control':8,'panel':12,'dialog':20,'small':4,'organic':12,'round':999}.items():css.append(f'  --r-semantic-radius-{name}: {val}px;')
for name,key in [('body','ui'),('editorial','editorial'),('code','code')]:css.append(f'  --r-semantic-font-{name}: {source["typography"][key]};')
for name,val in [('caption',12),('small',14),('body',16),('lead',20),('heading',28),('title',40),('display',64)]:css.append(f'  --r-semantic-size-{name}: {val/16:g}rem;')
for name,val in old_motion.items():css.append(f'  --r-semantic-motion-{name}: {val}ms;')
for name in ['standard','entrance','exit-ease','ease']:css.append(f'  --r-semantic-motion-{name}: {motion["easing"]};')
for name in ['small','dialog','panel','page']:css.append(f'  --r-semantic-motion-distance-{name}: 6px;')
css += ['  --r-component-button-height-small: 32px;', '  --r-component-button-height-medium: 40px;', '  --r-component-button-height-large: 48px;', '  --r-component-dialog-radius: var(--r-semantic-radius-dialog);', '}']
css='\n'.join(css)+'\n'
(design/'rosemary-tokens.css').write_text(css)
(root/'apps/passport_server/lib/src/utils/epass_tokens.dart').write_text("// Generated by scripts/sync_epass_tokens.py; Forma 1.2.0 / SDK 0.4.0.\nconst epassTokens = r'''\n"+css+"''';\n")
code=['// Generated by scripts/sync_epass_tokens.py; Forma 1.2.0 / SDK 0.4.0.', '// Source SHA256: '+hashlib.sha256((design/'epass-theme.json').read_bytes()).hexdigest(),"import 'package:flutter/material.dart';", "import 'package:rosemary_ui/rosemary_ui.dart';",'']
for mode,palette in product['themes'].items():
    cls='RosmEpass'+mode.title()+'Tokens'
    code.append(f'class {cls} {{')
    for name,value in palette.items():code.append(f'  static const {camel(name)} = Color(0xFF{value[1:]});')
    for name,role in aliases.items():code.append(f'  static const {camel(name)} = {camel(role)};')
    code.append('  static const accentHover = primary;')
    code.append('  static const colors = RosemaryColors('+ ', '.join(f'{camel(n)}: {camel(n)}' for n in roles)+');')
    code.append('}\n')
code.append('class RosmEpassMotion {')
for name,val in old_motion.items():code.append(f'  static const {camel(name)} = Duration(milliseconds: {val});')
for name in ['standard','entrance','exitEase']:code.append(f'  static const {name} = Cubic(0.2, 0.7, 0.2, 1);')
code += ['}', 'class RosmEpassGeometry { static const control = 8.0; static const panel = 12.0; static const dialog = 20.0; }','']
flutter=root/'packages/rosm_passport_flutter/lib/src/epass_tokens.dart'
flutter.write_text('\n'.join(code))
subprocess.run(['dart','format',str(flutter),str(root/'apps/passport_server/lib/src/utils/epass_tokens.dart')],check=True)

