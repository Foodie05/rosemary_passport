# The approved product mark is one geometry across SVG, email-independent server
# documents and Flutter. The official mother-brand bitmap is never modified.
mark = json.loads((design / 'epass-mark.json').read_text())
def svg_markup(resolve):
    layers = []
    for layer in mark['layers']:
        color = resolve(layer['role'])
        common = f' opacity="{layer["opacity"]}"'
        if layer['type'] == 'rect':
            attrs = ' '.join(f'{key}="{layer[key]}"' for key in ['x','y','width','height','rx'])
            paint = f'fill="none" stroke="{color}" stroke-width="{layer["stroke"]}"' if layer.get('stroke') else f'fill="{color}"'
            layers.append(f'<rect {attrs} {paint}{common}/>')
        else:
            path = ' '.join(' '.join(str(x) for x in cmd) for cmd in layer['commands'])
            layers.append(f'<path d="{path}" fill="{color}"{common}/>')
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="32" height="32" aria-hidden="true">' + ''.join(layers) + '</svg>'
(root / 'web/public/brand/epass.svg').write_text(svg_markup(lambda r: p[r]) + '\n')
server_mark = svg_markup(lambda r: 'var(--r-semantic-color-' + r + ')')
(root / 'apps/passport_server/lib/src/utils/epass_brand.dart').write_text("// Generated from epass-mark.json by scripts/sync_epass_tokens.py.\nconst epassBadgeMarkup = r'''" + server_mark + "''';\n")
brand_code = ["// Generated from epass-mark.json by scripts/sync_epass_tokens.py.", "import 'package:flutter/material.dart';", "void paintEpassBadge(Canvas canvas, Size size, Color primary, Color onPrimary) {", 'canvas.save();', 'canvas.scale(size.width / 64, size.height / 64);']
ops = {'M':'moveTo','L':'lineTo','Q':'quadraticBezierTo','C':'cubicTo','Z':'close'}
for index, layer in enumerate(mark['layers']):
    color = 'primary' if layer['role'] == 'primary' else 'onPrimary'
    paint = f'Paint()..color = {color}.withValues(alpha: {layer["opacity"]})'
    if layer.get('stroke'):
        paint += f'..style = PaintingStyle.stroke..strokeWidth = {layer["stroke"]}'
    if layer['type'] == 'rect':
        brand_code.append(f'canvas.drawRRect(RRect.fromRectAndRadius(const Rect.fromLTWH({layer["x"]}, {layer["y"]}, {layer["width"]}, {layer["height"]}), const Radius.circular({layer["rx"]})), {paint});')
    else:
        path = f'final p{index} = Path()' + ''.join('..' + ops[c[0]] + '(' + ', '.join(str(v) for v in c[1:]) + ')' for c in layer['commands']) + ';'
        brand_code += [path, f'canvas.drawPath(p{index}, {paint});']
brand_code += ['canvas.restore();', '}']
brand_file = root / 'packages/rosm_passport_flutter/lib/src/epass_brand.dart'
brand_file.write_text('\n'.join(brand_code) + '\n')
subprocess.run(['dart', 'format', str(brand_file), str(root / 'apps/passport_server/lib/src/utils/epass_brand.dart')], check=True)

