import React, { useState } from 'react';
import { createRoot } from 'react-dom/client';
import { flushSync } from 'react-dom';
import { MemoryRouter, useLocation } from 'react-router-dom';
import { AnimatePresence } from 'motion/react';
import { Loading } from '@rosemary-ui/react';
import { ThemeProvider } from '../../src/theme';
import { MotionPreferences, MotionToggle } from '../../src/design/MotionPreferences';
import { SelectionGroup, SelectionContent } from '../../src/design/SelectionMotion';
import { Link, changePage } from '../../src/design/NavigationMotion';
import { RouteEffects } from '../../src/components/RouteEffects';
import { Dialog } from '../../src/components/Dialog';
import { FormaButton, FormaInput } from '../../src/components/Forma';
import '../../src/styles.css';
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const frame = () => new Promise(resolve => requestAnimationFrame(resolve));
const timings = el => el?.getAnimations().map(a => ({ duration: a.effect.getTiming().duration, easing: a.effect.getTiming().easing, frames: a.effect.getKeyframes() })) || [];
function App() {
  const { pathname } = useLocation();
  const [selection, setSelection] = useState(0), [open, setOpen] = useState(false), [drawer, setDrawer] = useState(false), [busy, setBusy] = useState(false), [report, setReport] = useState('等待验证');
  async function run() {
    const results = []; const check = (name, pass, detail) => results.push({ name, pass: Boolean(pass), detail });
    const toggle = document.querySelector('.epass-motion');
    if (toggle.getAttribute('aria-pressed') === 'true') flushSync(() => toggle.click());
    await frame();
    const panel = document.querySelector('.test-panel');
    check('initial panel is static', timings(panel).length === 0);
    flushSync(() => setSelection(1));
    const entry = timings(panel)[0];
    check('tab fade 180ms / Forma curve / no displacement', entry?.duration === 180 && entry.easing === 'cubic-bezier(0.2, 0.7, 0.2, 1)' && entry.frames[0].transform === 'translateX(0px)', entry);
    check('one live form after tab switch', document.querySelectorAll('.test-panel form').length === 1);
    await pause(45); const opacity = getComputedStyle(panel).opacity;
    flushSync(() => setSelection(0));
    check('interruption resumes current opacity', Math.abs(Number(timings(panel)[0]?.frames[0].opacity) - Number(opacity)) < .05);
    flushSync(() => toggle.click());
    check('reduce motion cancels current tab', timings(panel).length === 0);
    flushSync(() => setSelection(1));
    check('reduce motion suppresses subsequent tab', timings(panel).length === 0);
    flushSync(() => toggle.click()); await frame();
    const trigger = document.querySelector('#open'); trigger.focus();
    flushSync(() => setOpen(true)); await frame();
    let dialog = document.querySelector('dialog');
    check('official dialog is native modal and owns focus', dialog?.matches(':modal') && dialog.contains(document.activeElement));
    check('dialog enters 260ms / Forma curve', timings(dialog).some(a => a.duration === 260 && a.easing === 'cubic-bezier(0.2, 0.7, 0.2, 1)'), timings(dialog));
    await pause(50); flushSync(() => setOpen(false)); await frame();
    check('modal retained through real 160ms exit', dialog.open && timings(dialog).some(a => a.duration === 160), timings(dialog));
    flushSync(() => setOpen(true)); await pause(290);
    check('reopening cancels stale exit', document.querySelector('dialog')?.matches(':modal'));
    flushSync(() => setOpen(false)); await pause(210);
    check('exit removes modal and restores trigger focus', !document.querySelector('dialog') && document.activeElement === trigger);
    flushSync(() => {setDrawer(true); setOpen(true);}); await frame();
    dialog = document.querySelector('dialog');
    check('drawer enters 220ms', timings(dialog).some(a => a.duration === 220), timings(dialog));
    flushSync(() => setOpen(false)); await frame();
    check('drawer exits 180ms', timings(dialog).some(a => a.duration === 180), timings(dialog));
    await pause(220); flushSync(() => {setDrawer(false); toggle.click(); setOpen(true);}); await frame();
    check('reduced overlay has no animation', timings(document.querySelector('dialog')).length === 0);
    flushSync(() => setOpen(false)); await frame();
    check('reduced overlay closes immediately', !document.querySelector('dialog'));
    flushSync(() => toggle.click()); await frame();
    flushSync(() => setBusy(true)); await pause(100);
    check('loading hidden before 300ms delay', document.querySelector('.rm-loading')?.dataset.visible === 'false');
    await pause(240);
    const loading = document.querySelector('.rm-loading');
    check('official two-facet loading after delay', loading.dataset.visible === 'true' && loading.querySelectorAll('.rm-fold-back, .rm-fold-front').length === 2);
    check('loading cycle 1200ms', getComputedStyle(loading.querySelector('.rm-fold-front')).animationDuration.split(',').every(value => value.trim() === '1.2s'));
    flushSync(() => setBusy(false)); await frame();
    check('completed loading stops immediately', loading.dataset.active === 'false');
    flushSync(() => toggle.click()); await frame();
    check('reduced loading is static', getComputedStyle(loading.querySelector('.rm-fold-front')).animationName === 'none');
    flushSync(() => toggle.click()); await frame();
    document.querySelector('#next').click();
    const observed = [];
    for (let i = 0; i < 26; i++) { await frame(); for (const a of document.getAnimations()) if (a.animationName === 'epass-page-in' && observed.length === 0) observed.push({duration:a.effect.getTiming().duration, frames:a.effect.getKeyframes()}); }
    check('page enters 220ms / 6px', observed.some(a => a.duration === 220 && a.frames[0].transform.includes('6px')), observed);
    check('new route receives focus', pathname !== '/register' && document.querySelector('#route-name').textContent === '/register' && document.querySelector('main').contains(document.activeElement));
    const updates = []; changePage('/register', '/login', () => updates.push('stale')); changePage('/register', '/forgot-password', () => updates.push('latest')); await pause(320);
    check('rapid navigation only commits latest operation', updates.join() === 'latest', updates);
    setReport(JSON.stringify({ passed: results.every(r => r.pass), results }, null, 2));
  }
  return <main tabIndex={-1} style={{padding:24,maxWidth:800}}><h1>Forma 动效验收</h1><p id="route-name">{pathname}</p><Link id="next" to="/register">测试导航</Link><SelectionGroup label="测试标签" value={selection}>{['A','B'].map((label,i)=><FormaButton type="button" key={label} aria-pressed={selection===i} onClick={()=>setSelection(i)}>{label}</FormaButton>)}</SelectionGroup><SelectionContent value={selection} className="test-panel"><form><FormaInput label={`当前表单 ${selection}`} /></form></SelectionContent><FormaButton id="open" type="button" onClick={()=>setOpen(true)}>打开弹窗</FormaButton><AnimatePresence>{open&&<Dialog key="test" className={drawer?'epass-dialog-navigation':''} title="测试弹窗" onClose={()=>setOpen(false)}><FormaInput label="测试输入" /></Dialog>}</AnimatePresence><Loading active={busy}/><MotionToggle/><FormaButton type="button" onClick={run}>运行动效验收</FormaButton><pre role="status">{report}</pre></main>;
}
createRoot(document.getElementById('root')).render(<MotionPreferences><ThemeProvider><MemoryRouter initialEntries={['/login']}><RouteEffects/><App/></MemoryRouter></ThemeProvider></MotionPreferences>);
